"""Deterministic lossless encoding, atlas metadata and original cue synthesis.

Artwork is generated by image_gen and preserved unchanged in source PNGs.
This script does not repaint, mask, mirror or resize character artwork.
"""
from pathlib import Path
import hashlib
import json
import math
import struct
import wave
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "dev/aw2/assets/than/base-v1"
MANIFEST = ROOT / "src/aw2/assets/than.base-v1.json"
URL = "/dev/aw2/assets/than/base-v1/"
STATES = ["idle", "move", "attack", "cast", "hit", "guard", "ultimate", "defeat"]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def encode(name):
    source = ASSETS / f"{name}.png"
    image = Image.open(source).convert("RGBA")
    alpha = image.getchannel("A")
    assert alpha.histogram()[0] > image.width * image.height * 0.1, name
    target = ASSETS / f"{name}.webp"
    image.save(target, "WEBP", lossless=True, method=6, exact=True)
    # Some encoders normalize invisible RGB. Compare visible RGBA, preserving alpha.
    encoded = Image.open(target).convert("RGBA")
    assert encoded.getchannel("A").tobytes() == alpha.tobytes(), name
    for original, packed in zip(image.getdata(), encoded.getdata()):
        assert original[3] == 0 or original == packed, name
    return {
        "id": f"aw2-than:{name}:base-v1", "url": URL + target.name,
        "width": image.width, "height": image.height,
        "sha256": digest(target), "bytes": target.stat().st_size,
        "source": {"path": str(source.relative_to(ROOT)), "sha256": digest(source)},
        "transparentFraction": round(alpha.histogram()[0] / (image.width * image.height), 6),
    }


def frames(name, xs, ys, labels, edge_tolerance=8):
    alpha = Image.open(ASSETS / f"{name}.png").getchannel("A")
    result = {}
    for row in range(len(ys) - 1):
        for col in range(len(xs) - 1):
            x, y, w, h = xs[col], ys[row], xs[col + 1] - xs[col], ys[row + 1] - ys[row]
            cell = alpha.crop((x, y, x + w, y + h))
            bounds = cell.point(lambda a: 255 if a >= 96 else 0).getbbox()
            assert bounds and min(bounds[0], bounds[1], w - bounds[2], h - bounds[3]) >= 2, (name, row, col, bounds)
            edges = [cell.crop(box).getextrema()[1] for box in [(0, 0, w, 1), (0, h - 1, w, h), (0, 0, 1, h), (w - 1, 0, w, h)]]
            assert max(edges) <= edge_tolerance, (name, row, col, edges)
            label = labels[row][col]
            result[label] = {"asset": name, "x": x, "y": y, "width": w, "height": h,
                             "anchorX": round((bounds[0] + bounds[2]) / 2, 2),
                             "anchorY": bounds[3] if name != "fx" else round((bounds[1] + bounds[3]) / 2, 2),
                             "visibleBounds": list(bounds), "maxEdgeAlpha": max(edges)}
    return result


def cue(name, length, notes, noise=0):
    rate = 22050
    target = ASSETS / f"{name}.wav"
    samples = []
    seed = 17
    for i in range(round(length * rate)):
        t = i / rate
        envelope = math.sin(math.pi * min(1, t / length)) ** 2
        tone = sum(math.sin(2 * math.pi * (frequency * t + sweep * t * t / 2)) * volume
                   for frequency, sweep, volume in notes)
        seed = (1664525 * seed + 1013904223) & 0xffffffff
        tone += ((seed / 0xffffffff) * 2 - 1) * noise
        samples.append(round(max(-0.8, min(0.8, tone * envelope)) * 32767))
    with wave.open(str(target), "wb") as output:
        output.setparams((1, 2, rate, len(samples), "NONE", "not compressed"))
        output.writeframes(struct.pack("<" + "h" * len(samples), *samples))
    return {"id": f"aw2-than:audio:{name}", "url": URL + target.name,
            "durationMs": round(length * 1000), "sampleRate": rate,
            "sha256": digest(target), "method": "original deterministic additive synthesis + seeded noise"}


def track(*keys):
    return [{"atMs": t, "x": x, "y": y, "rotation": rotation, "scale": scale, "opacity": opacity}
            for t, x, y, rotation, scale, opacity in keys]


def main():
    sources = {name: encode(name) for name in ["reference", "world", "battle", "portrait", "fx"]}
    all_frames = frames("world", [0, 313, 627, 940, 1254], [0, 318, 626, 930, 1254],
                        [[f"world.{direction}.{i}" for i in range(4)] for direction in ["down", "left", "right", "up"]])
    all_frames.update(frames("battle", [0, 384, 768, 1152, 1536], [0, 546, 1024],
                             [[f"battle.{state}" for state in STATES[:4]], [f"battle.{state}" for state in STATES[4:]]]))
    all_frames.update(frames("fx", [0, 313, 627, 940, 1254], [0, 313, 627, 940, 1254],
                             [[f"fx.{skill}.{i}" for i in range(4)] for skill in ["basic", "auto", "passive", "ultimate"]]))
